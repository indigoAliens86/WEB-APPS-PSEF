  exportResepCsv(itemsToExport?: ResepItem[]): void {
    const items = itemsToExport || this.resepListState();
    const headers = [
      'ID Resep',
      'No Registrasi',
      'Tanggal',
      'Tipe Resep',
      'Kategori',
      'Status Resep',
      'Prioritas',
      'Nama Pasien',
      'No RM',
      'Usia',
      'Dokter Penulis',
      'SIP Dokter',
      'Faskes Asal',
      'Diagnosis',
      'Skrining Administratif',
      'Skrining Farmasetis',
      'Skrining Klinis',
      'Apoteker Pengkaji',
      'Total Biaya Obat (Rp)',
    ];

    const rows = items.map((r) => [
      `"${r.id}"`,
      `"${r.noRegistrasi}"`,
      `"${r.tanggal}"`,
      `"${r.tipeResep}"`,
      `"${r.kategori}"`,
      `"${r.status}"`,
      `"${r.isUrgent ? 'CITO / Prioritas' : 'Rutin'}"`,
      `"${r.pasien.nama}"`,
      `"${r.pasien.noRm}"`,
      `"${r.pasien.usia}"`,
      `"${r.dokter.nama}"`,
      `"${r.dokter.sip}"`,
      `"${r.dokter.faskesAsal}"`,
      `"${r.pasien.diagnosis}"`,
      `"${r.skrining.kajianAdministratif.status}"`,
      `"${r.skrining.kajianFarmasetis.status}"`,
      `"${r.skrining.kajianKlinis.status}"`,
      `"${r.skrining.apotekerPengkaji.nama}"`,
      r.totalBiayaObat,
    ]);

    const csvContent = '\uFEFF' + [headers.join(','), ...rows.map((e) => e.join(','))].join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', `rekapitulasi_skrining_resep_${new Date().toISOString().slice(0, 10)}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }
